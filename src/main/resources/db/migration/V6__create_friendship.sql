CREATE TABLE friendships
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    requester_id    BIGINT          NOT NULL,
    receiver_id     BIGINT          NOT NULL,
    status          VARCHAR(20)     NOT NULL,
    created_at      TIMESTAMPTZ     NOT NULL,
    accepted_at     TIMESTAMPTZ     NULL,

    CONSTRAINT pk_friendships
        PRIMARY KEY (id),

    CONSTRAINT fk_friendships_requester_id
        FOREIGN KEY (requester_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_friendships_receiver_id
        FOREIGN KEY (receiver_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT ck_friendships_different_members
        CHECK (requester_id <> receiver_id),

    CONSTRAINT ck_friendships_status
        CHECK (status IN ('PENDING', 'ACCEPTED')),

    CONSTRAINT ck_friendships_status_fields
        CHECK (
            (status = 'PENDING' AND accepted_at IS NULL)
                OR
            (status = 'ACCEPTED' AND accepted_at IS NOT NULL)
            )
);

CREATE UNIQUE INDEX uq_friendships_member_pair
    ON friendships (
                    LEAST(requester_id, receiver_id),
                    GREATEST(requester_id, receiver_id)
        );