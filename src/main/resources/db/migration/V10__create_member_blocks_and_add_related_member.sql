CREATE TABLE member_blocks
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    blocker_id      BIGINT      NOT NULL,
    blocked_id      BIGINT      NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_member_blocks
        PRIMARY KEY (id),

    CONSTRAINT fk_member_blocks_blocker_id
        FOREIGN KEY (blocker_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_member_blocks_blocked_id
        FOREIGN KEY (blocked_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    -- 동일한 차단관계 중복 방지
    CONSTRAINT uq_member_blocks_blocker_id_blocked_id
        UNIQUE (blocker_id, blocked_id),

    CONSTRAINT ck_member_blocks_different_members
        CHECK (blocker_id <> blocked_id)
);

-- `나를 차단한 회원 기준`으로 하는 조회 필터링에 사용
CREATE INDEX idx_member_blocks_blocked_id_blocker_id
    ON member_blocks (blocked_id, blocker_id);

