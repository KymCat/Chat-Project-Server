CREATE TABLE administrators(
    member_id       BIGINT          NOT NULL,
    created_at      TIMESTAMPTZ     NOT NULL,

    CONSTRAINT pk_administrators
        PRIMARY KEY(member_id),

    CONSTRAINT fk_administrators_member_id
        FOREIGN KEY (member_id)
            REFERENCES members (id)
            ON DELETE RESTRICT
);

CREATE TABLE message_reports(
    id                          BIGINT          GENERATED BY DEFAULT AS IDENTITY,
    message_id                  BIGINT          NOT NULL,
    reporter_id                 BIGINT          NOT NULL,
    reported_member_id          BIGINT          NOT NULL,
    reason                      VARCHAR(30)     NOT NULL,
    details                     VARCHAR(500)    NULL,
    message_type_snapshot       VARCHAR(20)     NOT NULL,
    message_content_snapshot    TEXT            NULL,
    created_at                  TIMESTAMPTZ     NOT NULL,

    CONSTRAINT pk_message_reports
        PRIMARY KEY (id),

    CONSTRAINT fk_message_reports_message_id
        FOREIGN KEY (message_id)
            REFERENCES chat_messages (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_message_reports_reporter_id
        FOREIGN KEY (reporter_id)
            REFERENCES members (id)
            ON DELETE RESTRICT,

    CONSTRAINT fk_message_reports_reported_member_id
            FOREIGN KEY (reported_member_id)
                REFERENCES members (id)
                ON DELETE RESTRICT,

    CONSTRAINT uq_message_reports_reporter_id_message_id
        UNIQUE (reporter_id, message_id),

    CONSTRAINT ck_message_reports_reason
        CHECK (
            reason IN (
                'ABUSE',
                'SPAM',
                'SEXUAL_CONTENT',
                'OTHER'
            )
        ),

    CONSTRAINT ck_message_reports_message_type_snapshot
        CHECK (
            message_type_snapshot IN (
                'TEXT',
                'IMAGE',
                'FILE'
            )
        ),

    CONSTRAINT ck_message_reports_different_members
        CHECK (reporter_id <> reported_member_id)
);

CREATE INDEX idx_message_reports_created_at_id_desc
    ON message_reports (created_at DESC, id DESC);

CREATE INDEX idx_message_reports_reported_member_id
    ON message_reports (reported_member_id);